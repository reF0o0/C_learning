/*
第 2 章 基本数据类型 · 2.6 / 2.7 / 2.8 重点

2.6 本章扩充内容 —— 数据在机器里长什么样
  1. 1 位 = 1 bit，8 位 = 1 字节。正负用补码：正数 = 原码，负数 = 反码 + 1
  2. 整数存补码，实数存浮点（IEEE 754），字符存 ASCII 码
  3. 变量三属性：名字、类型、值。类型决定占几个字节、怎么解释这串二进制
  4. 内存按字节编号，每字节一个地址，用 & 取。Java 里没有 &
  5. 容量：1B = 8bit，1KB = 1024B，1MB = 1024KB，1GB = 1024MB
  6. int 范围 -2147483648 ~ 2147483647，再多就绕回去；float 只有约 7 位有效数字

2.7 知识点小结
  常量（十/八/十六进制、字符、字符串、宏常量）· 变量先定义后使用 · 标识符区分大小写、
  不能用关键字 · 基本类型分整型、实型、字符型 · sizeof 是运算符不是函数 ·
  = 从右往左结合且整个式子有值 · 字符本质是小整数

2.8 常见错误小结
  变量没初始化就用，拿到的是垃圾值不是 0    int x = 3.7; 得到 3，是截断不是四舍五入
  用了没声明的变量                           sizeof 的结果要用 %zu 输出
  溢出就变成负数                             '3' 是 51 不是 3，'A' + 1 得 66 不是 B
  Sum 和 sum 是两个变量                      if (a = 1) 永远为真，还改掉了 a
  标识符起成关键字就编译不过                 float 不要用 == 比较
*/

#include <stdio.h>

int main(void) {
    // 2.6-1 补码：-1 在内存里是 32 位全 1，用十六进制看就是 ffffffff
    int neg = -1;
    int big = 2147483647;
    printf("-1 的十六进制  %x\n", neg);
    printf("'A' 的 ASCII   %d\n", 'A');                              // 字符就是小整数
    printf("char %zu 字节，int %zu 字节\n", sizeof(char), sizeof(int)); // 类型定大小
    printf("int 最大值 + 1 %d\n", big + 1);                             // 溢出，绕回最小值
    printf("float          %f\n", 123456.789e4f);                      // 精度不够
    printf("double         %f\n", 123456.789e4);
    return 0;
}
// sizeof 的结果类型是 size_t，所以上面用 %zu 输出而不是 %d
